import type { Verb } from '../types';

/*
 * High-frequency verb reference.
 * Every form is listed in the order je, tu, il/elle/on, nous, vous, ils/elles
 * (impératif: tu, nous, vous). Forms never include the subject pronoun.
 * Reflexive verbs include the reflexive pronoun ("me lève").
 * Subjonctif forms are given without "que".
 */

const AVOIR_AUX = ['ai', 'as', 'a', 'avons', 'avez', 'ont'];

/** Passé composé with avoir, e.g. pcAvoir('parlé') -> ["ai parlé", ...]. */
const pcAvoir = (p: string): string[] => AVOIR_AUX.map((a) => `${a} ${p}`);

/** Passé composé with être, showing agreement, e.g. pcEtre('allé'). */
const pcEtre = (p: string): string[] => [
  `suis ${p}(e)`,
  `es ${p}(e)`,
  `est ${p}(e)`,
  `sommes ${p}(e)s`,
  `êtes ${p}(e)(s)`,
  `sont ${p}(e)s`,
];

/** Reflexive passé composé, e.g. pcRefl('levé') -> ["me suis levé(e)", ...]. */
const pcRefl = (p: string): string[] => [
  `me suis ${p}(e)`,
  `t'es ${p}(e)`,
  `s'est ${p}(e)`,
  `nous sommes ${p}(e)s`,
  `vous êtes ${p}(e)(s)`,
  `se sont ${p}(e)s`,
];

/** Futur simple from the future stem, e.g. futur('ir') -> ["irai", ...]. */
const futur = (stem: string): string[] =>
  ['ai', 'as', 'a', 'ons', 'ez', 'ont'].map((e) => stem + e);

/** Conditionnel présent from the future stem, e.g. cond('ir') -> ["irais", ...]. */
const cond = (stem: string): string[] =>
  ['ais', 'ais', 'ait', 'ions', 'iez', 'aient'].map((e) => stem + e);

/** Imparfait from the nous-stem, e.g. imparfait('parl') -> ["parlais", ...]. */
const imparfait = (stem: string): string[] =>
  ['ais', 'ais', 'ait', 'ions', 'iez', 'aient'].map((e) => stem + e);

/** Adds reflexive pronouns (with elision before a vowel or silent h). */
const refl = (forms: string[]): string[] => {
  const prons = ['me', 'te', 'se', 'nous', 'vous', 'se'];
  return forms.map((f, i) => {
    const p = prons[i];
    if ((p === 'me' || p === 'te' || p === 'se') && /^[aeiouyhéèêâîôû]/i.test(f)) {
      return `${p[0]}'${f}`;
    }
    return `${p} ${f}`;
  });
};

